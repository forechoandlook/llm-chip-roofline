export function cloneChip(chip) {
  return { ...chip };
}

export function chipById(id) {
  const c = CHIPS.find((x) => x.id === id);
  if (!c) throw new Error(`unknown chip ${id}`);
  return cloneChip(c);
}

/** Derived ratios used by the form and conclusions. */
export function chipRatios(chip) {
  const bf16 = Math.max(chip.bf16Tflops, 1e-9);
  return {
    vectorToMatmul: chip.vectorTflops / bf16,
    cubeToVector: bf16 / Math.max(chip.vectorTflops, 1e-9),
    bwPerMatmul: chip.hbmBandwidthGBs / bf16,
    fp4ToBf16: chip.fp4Tflops / bf16,
    fp8ToBf16: chip.fp8Tflops / bf16,
    ridgeBf16: (bf16 * 1e3) / Math.max(chip.hbmBandwidthGBs, 1e-9),
    ridgeFp8: (chip.fp8Tflops * 1e3) / Math.max(chip.hbmBandwidthGBs, 1e-9),
    ridgeFp4: (chip.fp4Tflops * 1e3) / Math.max(chip.hbmBandwidthGBs, 1e-9),
  };
}

export function applyDesignPoint(base, spec) {
  const chip = cloneChip(base);
  const bf16 = spec.bf16Tflops;
  chip.bf16Tflops = bf16;
  chip.fp8Tflops = bf16 * spec.fp8Mul;
  chip.fp4Tflops = bf16 * spec.fp4Mul;
  chip.fp32Tflops = bf16 * spec.fp32Mul;
  chip.vectorTflops = bf16 * spec.vectorToMatmul;
  chip.hbmBandwidthGBs = bf16 * spec.bwPerMatmul;
  if (spec.hbmCapacityGB != null) chip.hbmCapacityGB = spec.hbmCapacityGB;
  return chip;
}
